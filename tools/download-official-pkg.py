#!/usr/bin/env python3
"""Fetch the exact public 1.1-b132 PKG with browser-resolved MediaFire link.

No cookies, credentials, tokens, SDK binaries or alternative PKGs are trusted.
All downloads are checked against the maintainer's published size/SHA256.
"""
from pathlib import Path
from urllib.parse import urlparse
import argparse, hashlib, re, requests, time

OFFICIAL = "https://www.mediafire.com/file/5d0fd8diux8xvii/Android-TV-for-PS4-1.1-b132.pkg/file"
EXPECTED_BYTES = 3123380224
EXPECTED_SHA256 = "092b97255e12e6a6fbe4049b170c3a32acf0c9ecf2b6574c46deb48d8ae67286"
FILE = "Android-TV-for-PS4-1.1-b132.pkg"


def get_link(session):
    # The public download link is a short-lived URL generated by MediaFire.
    # Never commit a short-lived download URL into the repository.
    response = session.get(OFFICIAL, timeout=45)
    response.raise_for_status()
    text = response.text
    patterns = [
        r'<a\b(?=[^>]*\bid="downloadButton")(?=[^>]*\bhref="([^"]+)")',
        r'<a\b(?=[^>]*\bhref="([^"]+)")(?=[^>]*\bid="downloadButton")',
    ]
    from html import unescape
    for pattern in patterns:
        m = re.search(pattern, text, re.I | re.S)
        if m:
            return unescape(m.group(1))
    # MediaFire sometimes inserts the button through client-side JavaScript.
    from playwright.sync_api import sync_playwright
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True, args=["--no-sandbox"])
        try:
            page = browser.new_page(user_agent="Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36")
            page.goto(OFFICIAL, wait_until="domcontentloaded", timeout=60000)
            page.locator("#downloadButton").wait_for(state="attached", timeout=90000)
            return page.locator("#downloadButton").get_attribute("href")
        finally:
            browser.close()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    assert not args.output.exists(), "Refusing to overwrite an existing package"
    session = requests.Session()
    session.headers["User-Agent"] = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/130.0.0.0 Safari/537.36"
    for attempt in range(1, 4):
        href = get_link(session)
        parsed = urlparse(href or "")
        if parsed.scheme != "https" or not re.fullmatch(r"download\d+\.mediafire\.com", parsed.hostname or "") or "/5d0fd8diux8xvii/" not in parsed.path or not parsed.path.endswith("/" + FILE):
            raise SystemExit("MediaFire did not supply an authenticated public download link for expected file")
        print("MediaFire public download link resolved, downloading official PKG", flush=True)
        hashed = hashlib.sha256()
        size = 0
        try:
            with session.get(href, stream=True, timeout=(45, 180)) as response:
                response.raise_for_status()
                if response.headers.get("Content-Type", "").lower().startswith("text/html"):
                    raise ValueError("MediaFire returned HTML instead of PKG")
                with args.output.open("xb") as file:
                    for chunk in response.iter_content(chunk_size=4 * 1024 * 1024):
                        if chunk:
                            size += len(chunk)
                            if size > EXPECTED_BYTES:
                                raise ValueError("PKG larger than maintainer's pinned release")
                            hashed.update(chunk)
                            file.write(chunk)
            if size != EXPECTED_BYTES or hashed.hexdigest() != EXPECTED_SHA256:
                raise ValueError("PKG hash/size did not match original b132 release")
            print("PASS: exact b132 PKG SHA256 and size verified", flush=True)
            return
        except Exception as exc:
            args.output.unlink(missing_ok=True)
            if attempt == 3:
                raise SystemExit("Cannot acquire pinned b132 PKG: " + str(exc))
            print("Retrying fresh MediaFire link after download error:", str(exc), flush=True)
            time.sleep(3)


if __name__ == "__main__":
    main()
